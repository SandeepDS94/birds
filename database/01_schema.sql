-- ==============================================================================
-- 01_schema.sql
-- Database Schema for AI-Based Bird Sound Identification System
-- ==============================================================================

-- 1. Profiles table (linked to Supabase auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Birds species reference catalog
CREATE TABLE IF NOT EXISTS public.birds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name TEXT NOT NULL,
    scientific_name TEXT NOT NULL UNIQUE,
    family TEXT,
    "order" TEXT,
    description TEXT,
    habitat TEXT,
    diet TEXT,
    distribution TEXT,
    conservation_status TEXT,
    interesting_facts JSONB DEFAULT '[]'::JSONB,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. Identifications table (records user uploads and AI inference outcomes)
CREATE TABLE IF NOT EXISTS public.identifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    bird_name TEXT,
    scientific_name TEXT,
    confidence NUMERIC(5, 4),
    recording_duration NUMERIC(8, 2),
    identified_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    top_predictions JSONB DEFAULT '[]'::JSONB,
    audio_path TEXT,
    status TEXT DEFAULT 'identified' CHECK (status IN ('identified', 'low_confidence', 'no_detection'))
);

-- 4. Performance Indexes
CREATE INDEX IF NOT EXISTS idx_identifications_user_date 
    ON public.identifications(user_id, identified_at DESC);

CREATE INDEX IF NOT EXISTS idx_identifications_scientific 
    ON public.identifications(scientific_name);

CREATE INDEX IF NOT EXISTS idx_birds_scientific 
    ON public.birds(scientific_name);

CREATE INDEX IF NOT EXISTS idx_birds_common_name 
    ON public.birds(common_name);

-- 5. Auto-create user profile trigger on new user signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, created_at)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.email),
        NOW()
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger firing on auth.users insert
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
